"""Render results/ablations/*.json into results/ablations/README.md."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path("results/ablations")


def row(name: str, r: dict) -> str:
    m, (lo, hi), lat = r["metrics"], r["mrr_ci95"], r["latency_ms"]
    return (
        f"| {name} | {m['hit@1']:.3f} | {m['hit@5']:.3f} | {m['mrr@10']:.3f} | {lo:.2f}-{hi:.2f} "
        f"| {m['ndcg@10']:.3f} | {m['recall@10']:.3f} | {lat['p50']:.0f} |"
    )


HEADER = [
    "| Configuration | Hit@1 | Hit@5 | MRR@10 | 95% CI | nDCG@10 | Recall@10 | p50 ms |",
    "|---|---:|---:|---:|---:|---:|---:|---:|",
]


def main() -> None:
    out = [
        "# Ablations",
        "",
        "Generated by `.github/workflows/ablations.yml`; same 60 questions as the main benchmark.",
        "",
    ]

    models = sorted(p for p in ROOT.glob("*/results.json"))
    if models:
        out += ["## Model choices", ""]
        for mode in ("dense", "hybrid", "hybrid_rerank"):
            out += [f"### `{mode}`", "", *HEADER]
            for path in models:
                payload = json.loads(path.read_text())
                cfg = payload["config"]
                for r in payload["modes"]:
                    if r["mode"] == mode:
                        name = f"{cfg['embedding_model']}"
                        if mode.endswith("rerank"):
                            name += f" + {cfg['reranker_model']}"
                        r = {**r, "mrr_ci95": r.get("mrr_ci95", (0, 0))}
                        out.append(row(name, r))
            out.append("")

    sweep = ROOT / "sweep.json"
    if sweep.exists():
        rows = json.loads(sweep.read_text())
        for group, title in [("fusion", "Fusion method"), ("rerank_depth", "Rerank depth")]:
            out += [f"## {title}", "", *HEADER]
            out += [row(f"{r['setting']} ({r['mode']})", r) for r in rows if r["group"] == group]
            out.append("")

    (ROOT / "README.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
